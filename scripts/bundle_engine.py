"""Build the engine the deb and the AppImage carry: a CPython, its locked dependencies and `engine/`.

Until this existed a package held only the desktop shell, and the shell found its engine in a
checkout — so installing Codify meant also cloning it, having Python 3.10+ and running
`make setup` (`docs/18` §2). This builds the other half, once, into a directory the bundler
copies into both packages:

    build/engine-bundle/
        python/       python-build-standalone's CPython, pruned, with the lock installed
        engine/       the engine package, as it is in this checkout
        BUNDLE.json   what went in: the interpreter, the lock's hash, the app version

    python3 scripts/bundle_engine.py                     # into build/engine-bundle
    python3 scripts/bundle_engine.py --out /some/dir
    python3 scripts/bundle_engine.py --python-tarball cpython.tar.gz   # no download

**The interpreter is pinned, and checked.** `packaging/python.json` names one
python-build-standalone build and its SHA-256, and nothing else is accepted: a download, or a
tarball handed in with `--python-tarball`, whose hash differs is deleted and the build fails
naming both hashes. It is relocatable and needs only glibc 2.17, which is why it can sit at
`/usr/lib/Codify` in a deb or inside an AppImage's mount and still find its own standard
library. The minor version is the newest one `check.yml` tests, so the interpreter people run is
one CI already ran the suite on (`tests/test_bundle_engine.py` holds the two together).

**The dependencies are a lock, installed with hashes.** `packaging/engine.lock` is generated by
`make lock-engine` (`scripts/lock_engine.py`), never edited. It is installed with
`--require-hashes --no-deps --only-binary=:all:` and the same platform tags it was resolved
for, so the bundle holds exactly the wheels the lock names and a wheel that changed on PyPI
under the same version stops the build instead of shipping.

**What the bundle is run as decides how it is built.** It is read-only wherever it lands
(`/usr/lib/Codify` belongs to root, an AppImage is a squashfs), and neither package keeps a
file's modification time, so a `.pyc` checked against its source's timestamp would be stale on
every start and could not be rewritten — the engine would recompile its imports on every launch.
Everything is compiled here with `--invalidation-mode unchecked-hash` instead, and the shell
starts the bundle with `PYTHONDONTWRITEBYTECODE=1` (`engine_protocol::engine_env`).

Not bundled: the Laya gate's SDK (it brings torch; the gate keeps its LLM fallback, `docs/05`),
and anything `pip` would need at run time — `pip` itself is pruned once the lock is in.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess  # noqa: S404 — argv lists only, never a shell
import sys
import tarfile
import tempfile
import urllib.parse
import urllib.request
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
PIN_PATH = ROOT / "packaging" / "python.json"
LOCK_PATH = ROOT / "packaging" / "engine.lock"
DEFAULT_OUT = ROOT / "build" / "engine-bundle"
DEFAULT_CACHE = ROOT / "build" / "cache"
TAURI_CONF = ROOT / "src-tauri" / "tauri.conf.json"

# Where a pinned build can be fetched from, in order: the project's own releases, then the
# mirror Astral serves them from (the one `uv` uses). The hash is the same file's hash wherever
# it came from, so a second host adds availability and no trust.
MIRRORS = (
    "https://github.com/astral-sh/python-build-standalone/releases/download",
    "https://releases.astral.sh/github/python-build-standalone/releases/download",
)

# The oldest glibc the packages promise to run on: the `ubuntu-22.04` runner the release is built
# on (`docs/18` §3). Wheels are chosen for exactly this floor, newest tag first, which is what pip
# itself would choose on that system — so the lock and the install agree on every file.
GLIBC_FLOOR = (2, 35)
ARCH = "x86_64"

# Removed from the interpreter once the lock is installed: the GUI toolkit and its Tcl/Tk, the
# IDE and the turtle demos, the headers and manual pages, and the installers. The engine has no
# window of its own (the folder picker uses the system's GTK, `engine/app.py`) and installs
# nothing at run time. And the shared libpython, a third of the bundle: `bin/python3` is linked
# statically, and no extension module in the build or the lock links the library (`ldd` says so;
# the smoke test is what would notice if one started to).
PRUNE = (
    "bin/idle3",
    "bin/pip",
    "bin/pydoc3",
    "include",
    "share",
    "lib/itcl4.3.5",
    "lib/tcl9",
    "lib/tcl9.0",
    "lib/tk9.0",
    "lib/thread3.0.4",
    "lib/libtcl9.0.so",
    "lib/libtcl9tk9.0.so",
    "lib/libpython3.so",
    "lib/pkgconfig",
    "lib/python{minor}/idlelib",
    "lib/python{minor}/tkinter",
    "lib/python{minor}/turtledemo",
    "lib/python{minor}/ensurepip",
    "lib/python{minor}/site-packages/pip",
)
# Versioned siblings of the entries above (`bin/pip3.14`, `pip-26.1.2.dist-info`, `_tkinter.*.so`).
PRUNE_GLOBS = (
    "bin/idle3.*",
    "bin/pip3*",
    "bin/pydoc3.*",
    "bin/python3*-config",
    "lib/libpython{minor}.so*",
    "lib/python{minor}/site-packages/pip-*.dist-info",
    "lib/python{minor}/lib-dynload/_tkinter.*",
)

# What of `engine/` is not part of the engine a package runs.
SKIPPED_NAMES = frozenset({"__pycache__", "requirements.txt"})
SKIPPED_SUFFIXES = (".pyc", ".pyo")

PIP_TIMEOUT_S = 900
COMPILE_TIMEOUT_S = 600
DOWNLOAD_TIMEOUT_S = 120


class BundleError(RuntimeError):
    """A build that must stop, with the sentence that says why."""


@dataclass(frozen=True)
class Pin:
    version: str
    release: str
    asset: str
    sha256: str

    @property
    def minor(self) -> str:
        """`3.14` for `3.14.6`: the directory name under `lib/`, and the wheel ABI's number."""
        major, minor = self.version.split(".")[:2]
        return f"{major}.{minor}"

    @property
    def abi(self) -> str:
        return "cp" + self.minor.replace(".", "")


def load_pin(path: Path = PIN_PATH) -> Pin:
    """The pinned interpreter, refused when the pin does not describe one coherent build."""
    data = json.loads(path.read_text(encoding="utf-8"))
    pin = Pin(
        version=str(data["version"]),
        release=str(data["release"]),
        asset=str(data["asset"]),
        sha256=str(data["sha256"]).lower(),
    )
    if not re.fullmatch(r"[0-9a-f]{64}", pin.sha256):
        raise BundleError(f"{path}: sha256 is not 64 hex digits")
    if not re.fullmatch(r"\d+\.\d+\.\d+", pin.version):
        raise BundleError(f"{path}: version {pin.version!r} is not major.minor.patch")
    expected = f"cpython-{pin.version}+{pin.release}-{ARCH}-unknown-linux-gnu-install_only_stripped.tar.gz"
    if pin.asset != expected:
        raise BundleError(
            f"{path}: asset {pin.asset!r} is not the {pin.version} build from {pin.release} "
            f"(expected {expected!r})"
        )
    return pin


def asset_urls(pin: Pin) -> list[str]:
    """Every address the pinned file can be fetched from, `+` escaped as GitHub serves it."""
    name = urllib.parse.quote(pin.asset)
    return [f"{base}/{pin.release}/{name}" for base in MIRRORS]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def keep_if_pinned(path: Path, pin: Pin) -> None:
    """Accept `path` as the pinned interpreter, or delete it and say what it was instead."""
    actual = sha256_file(path)
    if actual != pin.sha256:
        path.unlink(missing_ok=True)
        raise BundleError(
            f"{pin.asset} has sha256 {actual}, and packaging/python.json pins {pin.sha256}; "
            "the file was deleted. A different file under the pinned name is never used."
        )


def _download(url: str, dest: Path) -> None:
    with urllib.request.urlopen(url, timeout=DOWNLOAD_TIMEOUT_S) as response:  # noqa: S310 — the URL is one of MIRRORS (https) with the pinned asset's name; nothing a person or a model typed
        with dest.open("wb") as out:
            shutil.copyfileobj(response, out)


def fetch_python(
    pin: Pin,
    cache: Path,
    *,
    tarball: Path | None = None,
    download: Callable[[str, Path], None] = _download,
) -> Path:
    """The pinned tarball in `cache`, downloaded once and checked every time it is used."""
    cache.mkdir(parents=True, exist_ok=True)
    cached = cache / pin.asset
    if tarball is not None:
        shutil.copyfile(tarball, cached)
        keep_if_pinned(cached, pin)
        return cached
    if cached.is_file():
        try:
            keep_if_pinned(cached, pin)
            return cached
        except BundleError:
            pass  # a stale or truncated cache entry is deleted by the check; fetch it again
    failures: list[str] = []
    for url in asset_urls(pin):
        partial = cached.with_suffix(".partial")
        try:
            download(url, partial)
        except OSError as exc:
            partial.unlink(missing_ok=True)
            failures.append(f"{url}: {exc}")
            continue
        partial.replace(cached)
        keep_if_pinned(cached, pin)
        return cached
    raise BundleError("could not fetch the pinned CPython from any mirror:\n  " + "\n  ".join(failures))


def extract_python(tarball: Path, dest: Path) -> Path:
    """Unpack the tarball into `dest` and return the interpreter's root (`dest/python`)."""
    if not hasattr(tarfile, "data_filter"):
        raise BundleError(
            "this Python has no tarfile extraction filters (3.10.12 and later do); "
            "run the build with a newer interpreter"
        )
    dest.mkdir(parents=True, exist_ok=True)
    try:
        with tarfile.open(tarball, mode="r:gz") as archive:
            # `data` refuses absolute paths, `..`, links out of `dest` and device files.
            archive.extractall(dest, filter="data")
    except (tarfile.TarError, OSError) as exc:
        raise BundleError(f"{tarball.name} could not be unpacked safely: {exc}") from exc
    root = dest / "python"
    if not (root / "bin" / "python3").exists():
        raise BundleError(f"{tarball.name} holds no python/bin/python3")
    return root


def platform_tags(floor: tuple[int, int] = GLIBC_FLOOR) -> list[str]:
    """The manylinux tags a wheel may carry to run on `floor`, newest first, as pip ranks them."""
    major, newest = floor
    tags = [f"manylinux_{major}_{minor}_{ARCH}" for minor in range(newest, 16, -1)]
    return [*tags, f"manylinux2014_{ARCH}"]


def target_flags(pin: Pin) -> list[str]:
    """What pip is told about the interpreter the wheels are for — shared with the lock."""
    flags = ["--only-binary=:all:", "--implementation", "cp", "--python-version", pin.minor, "--abi", pin.abi]
    for tag in platform_tags():
        flags += ["--platform", tag]
    return flags


def site_packages(python_root: Path, pin: Pin) -> Path:
    return python_root / "lib" / f"python{pin.minor}" / "site-packages"


def install_argv(python: Path, python_root: Path, pin: Pin, lock: Path) -> list[str]:
    return [
        str(python), "-m", "pip", "install",
        "--disable-pip-version-check", "--no-input", "--no-compile", "--no-deps", "--root-user-action=ignore",
        "--require-hashes", "--upgrade",
        "--target", str(site_packages(python_root, pin)),
        *target_flags(pin),
        "-r", str(lock),
    ]


def prune(python_root: Path, pin: Pin) -> list[str]:
    """Remove `PRUNE` and `PRUNE_GLOBS` from the interpreter; returns what was removed."""
    removed: list[str] = []
    paths = [python_root / entry.format(minor=pin.minor) for entry in PRUNE]
    for pattern in PRUNE_GLOBS:
        paths += sorted(python_root.glob(pattern.format(minor=pin.minor)))
    for path in paths:
        if path.is_symlink() or path.is_file():
            path.unlink()
        elif path.is_dir():
            shutil.rmtree(path)
        else:
            continue
        removed.append(str(path.relative_to(python_root)))
    return removed


def _skipped(name: str) -> bool:
    return name in SKIPPED_NAMES or name.endswith(SKIPPED_SUFFIXES)


def copy_engine(src: Path, dest: Path) -> int:
    """Copy the engine package without its bytecode or its requirements file; returns the file count."""
    shutil.copytree(src, dest, ignore=lambda _dir, names: [n for n in names if _skipped(n)])
    return sum(1 for path in dest.rglob("*") if path.is_file())


def compile_argv(python: Path, paths: Iterable[Path]) -> list[str]:
    return [
        str(python), "-m", "compileall", "-q", "-f", "-j", "0",
        "--invalidation-mode", "unchecked-hash",
        *[str(path) for path in paths],
    ]


def app_version(conf: Path = TAURI_CONF) -> str:
    return str(json.loads(conf.read_text(encoding="utf-8"))["version"])


def manifest(pin: Pin, lock_text: str, version: str, engine_files: int) -> dict[str, Any]:
    """`BUNDLE.json`: enough to say, from an installed package, what its engine was built from."""
    return {
        "app_version": version,
        "python": {"version": pin.version, "release": pin.release, "sha256": pin.sha256},
        "lock_sha256": hashlib.sha256(lock_text.encode("utf-8")).hexdigest(),
        "packages": sorted(
            line.split(" ", 1)[0]
            for line in lock_text.splitlines()
            if line.strip() and not line.startswith("#")
        ),
        "engine_files": engine_files,
    }


def _run(argv: list[str], what: str, timeout_s: int) -> None:
    env = {k: v for k, v in os.environ.items() if k not in ("PYTHONHOME", "PYTHONPATH")}
    env["PYTHONNOUSERSITE"] = "1"
    try:
        done = subprocess.run(argv, env=env, timeout=timeout_s, check=False)  # noqa: S603 — argv is install_argv/compile_argv: the pinned interpreter's own pip and compileall over paths this script made; no shell
    except subprocess.TimeoutExpired as exc:
        raise BundleError(f"{what} did not finish within {timeout_s}s") from exc
    if done.returncode != 0:
        raise BundleError(f"{what} exited {done.returncode}")


def _make_room(out: Path) -> None:
    """Clear `out` for a new bundle — but only an old bundle or nothing, never someone's directory."""
    if not out.exists():
        return
    if (out / "BUNDLE.json").is_file() or not any(out.iterdir()):
        shutil.rmtree(out)
        return
    raise BundleError(f"{out} exists and is not an engine bundle; it is left as it is")


def build(out: Path, cache: Path, *, tarball: Path | None = None) -> dict[str, Any]:
    pin = load_pin()
    lock_text = LOCK_PATH.read_text(encoding="utf-8")
    _make_room(out)
    archive = fetch_python(pin, cache, tarball=tarball)
    # Built beside `out` and renamed into place, so an interrupted build leaves no half-bundle
    # where the packager would pick it up.
    out.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".engine-bundle-", dir=out.parent))
    try:
        python_root = extract_python(archive, staging)
        python = python_root / "bin" / "python3"
        _run(install_argv(python, python_root, pin, LOCK_PATH), "installing packaging/engine.lock", PIP_TIMEOUT_S)
        prune(python_root, pin)
        engine_files = copy_engine(ROOT / "engine", staging / "engine")
        _run(
            compile_argv(python, [python_root / "lib" / f"python{pin.minor}", staging / "engine"]),
            "compiling the bundle",
            COMPILE_TIMEOUT_S,
        )
        info = manifest(pin, lock_text, app_version(), engine_files)
        (staging / "BUNDLE.json").write_text(json.dumps(info, indent=2) + "\n", encoding="utf-8")
        staging.replace(out)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return info


def _size(path: Path) -> int:
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file() and not p.is_symlink())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="where the bundle goes")
    parser.add_argument("--cache", type=Path, default=DEFAULT_CACHE, help="where the CPython download is kept")
    parser.add_argument(
        "--python-tarball", type=Path, default=None,
        help="use this file instead of downloading; it must still match packaging/python.json",
    )
    args = parser.parse_args(argv)
    try:
        info = build(args.out.resolve(), args.cache.resolve(), tarball=args.python_tarball)
    except BundleError as exc:
        print(f"bundle-engine: {exc}", file=sys.stderr)
        return 1
    size_mb = _size(args.out) / 1e6
    print(
        f"bundle-engine: {args.out} — CPython {info['python']['version']}, "
        f"{len(info['packages'])} packages, {info['engine_files']} engine files, {size_mb:.0f} MB"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
